function slugify(input: string): string {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

const CATEGORY_PREFIX: Record<SupportCategory, string> = {
  Hardware: 'HW',
  Software: 'SW',
  Network: 'NW',
  Account: 'AC',
  Security: 'SC',
};

export function createSeedArticles(): Article[] {
  const now = Date.now();
  const categoryCounters: Record<SupportCategory, number> = {
    Hardware: 0,
    Software: 0,
    Network: 0,
    Account: 0,
    Security: 0,
  };

  return RAW_ARTICLES.map((raw, idx) => {
    categoryCounters[raw.category] += 1;
    const seq = String(categoryCounters[raw.category]).padStart(3, '0');
    const code = `KB-${CATEGORY_PREFIX[raw.category]}-${seq}`;
    const updatedDate = new Date(now - raw.daysAgo * 86400_000).toISOString();
    const createdDate = new Date(
      now - (raw.daysAgo + 45) * 86400_000
    ).toISOString();

    return {
      _id: `art_${String(idx + 1).padStart(4, '0')}`,
      code,
      title: raw.title,
      slug: slugify(raw.title),
      type: raw.type,
      category: raw.category,
      subcategory: raw.subcategory,
      summary: raw.summary,
      overview: raw.overview,
      steps: raw.steps,
      errorCodes: raw.errorCodes ?? [],
      keywords: raw.keywords,
      helpfulCount: raw.helpful,
      notHelpfulCount: raw.notHelpful,
      views: raw.views,
      status: 'published',
      author: raw.author,
      updatedAt: updatedDate,
      createdAt: createdDate,
    };
  });
}

